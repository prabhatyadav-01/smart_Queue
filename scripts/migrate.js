async function migrateData(sqliteDb, pgClientOrPool, { reset = false } = {}) {
  console.log('[migrate] Initializing Postgres schema...');
  await pgClientOrPool.query(SCHEMA_SQL);

  const stats = {};

  for (const table of TABLES) {
    const sqliteRows = sqliteDb.prepare(`SELECT * FROM "${table.name}"`).all();
    console.log(`[migrate] Transferring ${table.name} (${sqliteRows.length} rows)...`);

    if (reset) {
      await pgClientOrPool.query(`DELETE FROM "${table.name}"`);
    }

    if (sqliteRows.length > 0) {
      const colList = table.cols.map((c) => `"${c}"`).join(', ');
      for (const row of sqliteRows) {
        const values = table.cols.map((col) => {
          let val = row[col];
          if (val === undefined) val = null;
          return val;
        });
        const placeholders = values.map((_, i) => `$${i + 1}`).join(', ');
        const query = `INSERT INTO "${table.name}" (${colList}) VALUES (${placeholders}) ON CONFLICT DO NOTHING`;
        await pgClientOrPool.query(query, values);
      }
    }

    if (table.seq) {
      try {
        await pgClientOrPool.query(
          `SELECT setval(pg_get_serial_sequence($1, 'id'), COALESCE((SELECT MAX(id) FROM "${table.name}"), 1))`,
          [table.name]
        );
      } catch {
        // Fallback for pg-mem or direct sequence name
        try {
          await pgClientOrPool.query(
            `SELECT setval('${table.name}_id_seq', COALESCE((SELECT MAX(id) FROM "${table.name}"), 1))`
          );
        } catch {
          // ignore sequence error if not supported in emulator
        }
      }
    }

    const countRes = await pgClientOrPool.query(`SELECT COUNT(*) AS c FROM "${table.name}"`);
    const pgCount = Number.parseInt(countRes.rows[0].c, 10);
    stats[table.name] = { sqlite: sqliteRows.length, postgres: pgCount };
  }

  console.log('\n[migrate] Migration verification summary:');
  let allMatched = true;
  for (const [t, s] of Object.entries(stats)) {
    const match = s.sqlite === s.postgres;
    if (!match) allMatched = false;
    console.log(`  - ${t}: SQLite = ${s.sqlite}, Postgres = ${s.postgres} ${match ? '✔' : '❌ MISMATCH'}`);
  }

  if (!allMatched) {
    throw new Error('Migration verification failed: row counts do not match!');
  }

  console.log('\n[migrate] All row counts verified successfully!');
  return stats;
}

function generateSqlDump(sqliteDb) {
  let sql = `-- SmartQueue SQLite to Supabase Postgres Migration Dump
-- Generated at: ${new Date().toISOString()}

`;
  for (const table of TABLES) {
    const rows = sqliteDb.prepare(`SELECT * FROM "${table.name}"`).all();
    if (!rows.length) continue;
    sql += `-- Table: ${table.name} (${rows.length} rows)\n`;
    const colList = table.cols.map((c) => `"${c}"`).join(', ');
    for (const row of rows) {
      const vals = table.cols.map((col) => {
        const val = row[col];
        if (val === null || val === undefined) return 'NULL';
        if (typeof val === 'number') return val;
        // Escape string
        return `'${String(val).replace(/'/g, "''")}'`;
      });
      sql += `INSERT INTO "${table.name}" (${colList}) VALUES (${vals.join(', ')}) ON CONFLICT DO NOTHING;\n`;
    }
    if (table.seq) {
      sql += `SELECT setval(pg_get_serial_sequence('${table.name}', 'id'), COALESCE((SELECT MAX(id) FROM "${table.name}"), 1));\n`;
    }
    sql += '\n';
  }
  return sql;
}

module.exports = { SCHEMA_SQL, RLS_SQL, TABLES, migrateData, generateSqlDump };

if (require.main === module) {
  const dbUrl = process.env.DATABASE_URL || process.env.SUPABASE_DB_URL;
  const sqlitePath = process.env.SQLITE_DB || path.resolve(__dirname, '../data/queue.db');
  const dumpPath = path.resolve(__dirname, '../supabase/migrations/20260310000001_migrated_data.sql');

  if (!dbUrl) {
    if (fs.existsSync(sqlitePath)) {
      console.log('[migrate] No DATABASE_URL specified. Generating Supabase SQL dump from SQLite...');
      const { DatabaseSync } = require('node:sqlite');
      const sqliteDb = new DatabaseSync(sqlitePath);
      const dump = generateSqlDump(sqliteDb);
      fs.mkdirSync(path.dirname(dumpPath), { recursive: true });
      fs.writeFileSync(dumpPath, dump, 'utf8');
      console.log(`[migrate] Migrated SQL dump written to: ${dumpPath}`);
    } else {
      console.log('[migrate] No DATABASE_URL specified and no SQLite file found.');
      console.log(`[migrate] Pre-generated migration dump is available at: ${dumpPath}`);
    }
    console.log('[migrate] To migrate directly into a live Supabase Postgres database, set DATABASE_URL:');
    console.log('          DATABASE_URL="postgresql://postgres:[password]@db.[project-ref].supabase.co:5432/postgres" npm run migrate');
    process.exit(0);
  }

  console.log('[migrate] Connecting to target Postgres database...');
  const pool = new pg.Pool({
    connectionString: dbUrl,
    ssl: dbUrl.includes('localhost') ? false : { rejectUnauthorized: false },
  });

  (async () => {
    // 1. Ensure schema and RLS policies exist
    console.log('[migrate] Ensuring schema is up to date...');
    await pool.query(SCHEMA_SQL);
    console.log('[migrate] Ensuring Row Level Security (RLS) is enabled...');
    await pool.query(RLS_SQL);

    // 2. If SQLite file exists, migrate live
    if (fs.existsSync(sqlitePath)) {
      console.log(`[migrate] Migrating live from SQLite database (${sqlitePath})...`);
      const { DatabaseSync } = require('node:sqlite');
      const sqliteDb = new DatabaseSync(sqlitePath);
      const stats = await migrateData(sqliteDb, pool);
      console.log('\n[migrate] Migration completed successfully!', stats);
    } else if (fs.existsSync(dumpPath)) {
      console.log(`[migrate] Applying pre-generated SQL migration dump (${dumpPath})...`);
      const dumpSql = fs.readFileSync(dumpPath, 'utf8');
      await pool.query(dumpSql);
      console.log('\n[migrate] Migration dump applied successfully!');
    } else {
      console.warn('[migrate] Neither SQLite database nor migration SQL dump found.');
    }
  })()
    .then(async () => {
      await pool.end();
      process.exit(0);
    })
    .catch(async (err) => {
      console.error('\n[migrate] Migration failed:', err);
      await pool.end();
      process.exit(1);
    });
}

